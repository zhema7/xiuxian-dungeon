function bake(scene: Phaser.Scene, key: string) {
  const def = DEFS[key]
  if (!def) return
  const [w, h, px] = def
  const g = scene.make.graphics({ x: 0, y: 0 }, false)
  for (const [x, y, pw, ph, c] of px) {
    g.fillStyle(c, 1)
    g.fillRect(x, y, pw, ph)
  }
  g.generateTexture(key, w, h)
  g.destroy()
}

/** 仅为缺失（外部文件加载失败）的 key 生成兜底贴图 */
export function generateMissing(scene: Phaser.Scene, missingKeys: Iterable<string>) {
  for (const key of missingKeys) bake(scene, key)
}
